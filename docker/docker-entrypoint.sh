#!/bin/bash
# Gita Docker entrypoint script
# Generates config.toml from environment variables, then starts the server

set -euo pipefail

CONFIG_DIR="/app/config"
CONFIG_FILE="${CONFIG_DIR}/gita.toml"

# Create config directory
mkdir -p "${CONFIG_DIR}"

# Generated config at startup. `GITA_SERVER_JWT_SECRET` takes precedence;
# `JWT_SECRET` is accepted as an alias (used by `podman run --env-file .env`).
jwt_secret="${GITA_SERVER_JWT_SECRET:-${JWT_SECRET:-dev-secret-change-me}}"

# SSH listener configuration (optional). Only emitted when explicitly enabled.
ssh_enabled="${GITA_SERVER_SSH_ENABLED:-false}"

cat > "${CONFIG_FILE}" <<EOF
# Gita configuration - generated from environment variables at container startup
# Do not edit this file directly; use environment variables instead.

[server]
host = "${GITA_SERVER_HOST:-0.0.0.0}"
port = ${GITA_SERVER_PORT:-3000}
data_dir = "${GITA_SERVER_DATA_DIR:-/data}"
database_url = "${GITA_SERVER_DATABASE_URL:-postgres://gita:gita@postgres:5432/gita}"
jwt_secret = "${jwt_secret}"

[server.ssh]
enabled = ${ssh_enabled}
host = "${GITA_SERVER_SSH_HOST:-0.0.0.0}"
port = ${GITA_SERVER_SSH_PORT:-2222}

# Pages static-site serving (GitHub Pages style).
pages_enabled = ${GITA_SERVER_PAGES_ENABLED:-true}
pages_url_prefix = "${GITA_SERVER_PAGES_URL_PREFIX:-}"
EOF

# Optionally include a custom host key path (volume-mounted secret).
if [ -n "${GITA_SERVER_SSH_HOST_KEY:-}" ]; then
  cat >> "${CONFIG_FILE}" <<EOF
host_key = "${GITA_SERVER_SSH_HOST_KEY}"
EOF
fi

# Execute the server with the generated config. The binary resolves the
# frontend from its own location (<exe_dir>/web/dist), so no `cd` is needed.
exec /app/gita-server -c "${CONFIG_FILE}" "$@"